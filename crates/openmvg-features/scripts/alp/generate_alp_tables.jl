using Printf
using SHA

include("kernel_model.jl")
include("scale_model.jl")

const GENERATOR_VERSION = "4"
const SIGMAS_BITS_SHA256 = "020087eaeb96d8a7e701ccdc7545839223e9aaad92f3b50617d0b2036477b599"
const SPATIAL_BITS_SHA256 = "7eea90997766cdca9be87adc856617b81217c429c26d092b6a70e778b14da4dd"
const SCALE_ROW_MAJOR_LE_SHA256 = "edbf0e59d94e65cb6d3b153d121603c4a3876a63895f87453e11781379c0bbf6"
const Q_SAMPLE_ORDER = (0, 3, 6, 1, 4, 7, 2, 5, 8)

function rust_float(value::Float32)
    text = string(value)
    return occursin('.', text) || occursin('e', text) || occursin('E', text) ? text : text * ".0"
end

function bits_digest(values)
    io = IOBuffer()
    for value in values
        @printf(io, "%08x,", reinterpret(UInt32, value))
    end
    return bytes2hex(sha256(take!(io)))
end

function row_major_digest(transform)
    bytes = UInt8[]
    for row in eachrow(transform), value in row
        bits = reinterpret(UInt32, value)
        for shift in (0, 8, 16, 24)
            push!(bytes, UInt8((bits >> shift) & 0xff))
        end
    end
    return bytes2hex(sha256(bytes))
end

function emit_rows(io, rows, name, row_length)
    println(io, "#[rustfmt::skip]")
    println(io, "pub(super) const $name: [[f32; $row_length]; $(length(rows))] = [")
    for row in rows
        println(io, "    [")
        for first in 1:min(row_length, 9):length(row)
            last = min(first + min(row_length, 9) - 1, length(row))
            println(io, "        ", join(rust_float.(row[first:last]), ", "), ",")
        end
        println(io, "    ],")
    end
    println(io, "];\n")
end

function reference_cases(transform)
    specifications = [
        (name = "zero", samples = zeros(Float32, 4)),
        (name = "constant", samples = fill(100.0f0, 4)),
        (name = "interior_minimum", samples = Float32[-0.13, -0.42, -0.37, -0.11]),
        (name = "interior_maximum", samples = Float32[0.13, 0.42, 0.37, 0.11]),
        (name = "large_reference", samples = Float32[101.0, 98.0, 100.5, 100.0]),
    ]
    return map(specifications) do specification
        coefficients = ALPScaleModel.apply_transform(transform, specification.samples)
        merge(specification, (; coefficients))
    end
end

hex_bits(values) = join((@sprintf("0x%08x", reinterpret(UInt32, value)) for value in values), ", ")

function generated_rust(sigmas, transform, spatial_tables, cases)
    io = IOBuffer()
    println(io, "// SPDX-FileCopyrightText: 2026 Pierre Moulon and OpenMVG Rust contributors")
    println(io, "// SPDX-License-Identifier: MIT OR Apache-2.0\n")
    println(io, "// @generated by scripts/alp/generate_alp_tables.jl")
    println(io, "// Generator version: $GENERATOR_VERSION. Do not edit by hand.\n")
    println(io, "pub(crate) const SIGMAS: [f32; 4] = [", join(rust_float.(sigmas), ", "), "];\n")
    println(io, "pub(super) const Q_SAMPLE_ORDER: [usize; 9] = [", join(Q_SAMPLE_ORDER, ", "), "];\n")
    emit_rows(io, collect.(eachrow(transform)), "ALP_SCALE_CUBIC_BASE", 4)
    emit_rows(io, spatial_tables, "ALP_SPATIAL_QUADRATIC_BASE", 45)
    println(io, "#[cfg(test)]")
    println(io, "pub(super) struct AlpScaleReferenceCase {")
    println(io, "    pub(super) name: &'static str,")
    println(io, "    pub(super) sample_bits: [u32; 4],")
    println(io, "    pub(super) coefficient_bits: [u32; 4],")
    println(io, "}\n")
    println(io, "#[cfg(test)]\n#[rustfmt::skip]")
    println(io, "pub(super) const ALP_SCALE_REFERENCE_CASES: &[AlpScaleReferenceCase] = &[")
    for case in cases
        println(io, "    AlpScaleReferenceCase {")
        println(io, "        name: \"", case.name, "\",")
        println(io, "        sample_bits: [", hex_bits(case.samples), "],")
        println(io, "        coefficient_bits: [", hex_bits(case.coefficients), "],")
        println(io, "    },")
    end
    println(io, "];")
    return String(take!(io))
end

function generated_report(sigmas, model, cases, rust)
    return """
    # ALP generated-table report

    Generated with Julia `$(VERSION)`, generator version `$GENERATOR_VERSION`.

    - Rust artifact SHA-256: `$(bytes2hex(sha256(rust)))`
    - Scale matrix SHA-256, row-major little-endian Float32: `$(row_major_digest(model.transform))`
    - Sample-sigma bit digest: `$(bits_digest(sigmas))`
    - Spatial-Q bit digest: `$SPATIAL_BITS_SHA256`

    ## Finite response objective

    Four level responses map to `[a,b,c,d]` in `P(σ)=aσ³+bσ²+cσ+d`.
    The fit minimizes equal-weight Gaussian and sinusoidal response error.
    Each input and target profile is divided by its integrated response norm
    `N²=⟨R(s)²⟩`, with the profile average uniform in log scale over the four-node
    interval. The constant-response constraint is `T·1=[0,0,0,1]ᵀ`.

    ```text
    E[⟨(v(s)ᵀ T r - R(s))²⟩log(s) / ⟨R(s)²⟩log(s)],
    v(s) = [s³,s²,s,1],  T·1 = [0,0,0,1]ᵀ.
    ```

    Here `r` contains the four input responses and `R(s)` is the target profile.

    Gaussian inputs are `exp(-r²/(2(σ²+b²)))` with phase uniform in
    `[-0.5,0.5]²`. Wave inputs are `exp(-b²k²/2)·cos(k(cosθ x+sinθ y))`, with `k=√2/σ`
    and direction uniform in `[0,π/2]`. The bases `b=0.5` and `b=1.6` have equal
    weight. Characteristic sigma is uniform in log scale over
    `[1.9027314f0,4.1498866f0]`.

    The quadrature uses 32 characteristic scales, 3 points per phase coordinate,
    and 8 wave directions. Target-profile integration uses 12 points per interval
    split at Gaussian-radius transitions `√(b²+(j/3)²)`. The four sample nodes
    are `$(join(rust_float.(sigmas), ", "))`.

    The model uses normalized finite Gaussian coefficients, radius `ceil(3τ)`,
    `τ=max(√(s²-b²),0.1)`, and a five-point `s²` Laplacian in Float32. Its
    convolution order is vertical then horizontal; runtime image filtering is
    horizontal then vertical. Rounding can differ between these orders.
    Gaussian normalization applies its known finite peak before the integrated
    norm; both normalization stages, quadrature, and QR use Float64.

    Sigma is centered and scaled to `[-1,1]`. A fixed orthonormal contrast basis
    eliminates the constant constraint, leaving 12 variables for a QR solve.
    The matrix is converted to physical-sigma coefficients and rounded to Float32.

    - Weighted design rows: `$(model.row_count)`
    - Design condition: `$(@sprintf("%.9g", model.design_condition))`
    - Weighted residual norm, `sqrt(weighted SSE)`: `$(@sprintf("%.9g", model.weighted_residual_norm))`

    ## Float32 evaluation

    All 16 fitted weights are serialized. Runtime uses the first three quantized
    weights per row and sets `δj=rj-r3`, `j=0..2`. Each row starts with
    `value=T[row,0]*δ0`, then adds `T[row,1]*δ1` and `T[row,2]*δ2`.
    The constant row adds `r3` to that sum. The effective fourth column follows
    the constant constraint; the stored fourth entry is the independently rounded
    fit value. Equal finite responses give a flat polynomial by this arithmetic.
    Rust consumes $(length(cases)) generated coefficient reference vectors covering
    zero, constant, signed interior responses, and a large constant reference.

    ## Spatial localization

    Nominal nodes are `(8/5)·√2^k`, `k=0..3`, serialized to six decimal places.
    The spatial model uses the analytic scale-normalized LoG
    `K(x,y,s)=((x²+y²)/s²-2)·exp(-(x²+y²)/(2s²))/s²`, a 19×19 integer kernel
    lattice, nine integer shifts, and a 21×21 offset grid in `[-1,1]²`.
    Two QR solves fit the quadratic basis `[x²,y²,xy,x,y,1]` and project its
    coefficient kernels onto the nine samples. Square-domain symmetries are
    imposed at 192-bit precision before six-decimal rounding and Float32 conversion.
    Exact zero signs are specified by four serialization masks.
    Runtime row-major patches use permutation `[0,3,6,1,4,7,2,5,8]`.

    ## References

    - G. Koutaki and K. Uchimura, *Scale-space Processing Using Polynomial
      Representations*, CVPR, 2014.
    - G. H. Golub and J. H. Welsch, *Calculation of Gauss Quadrature Rules*,
      Mathematics of Computation 23(106), 1969.
    """
end

function write_or_check(path, text, check)
    if check
        isfile(path) && read(path, String) == text || error("generated file differs: $path")
    else
        write(path, text)
    end
end

function main_tables()
    all(argument -> argument == "--check", ARGS) || error("unknown generator argument")
    check = "--check" in ARGS
    sigmas = ALPKernelModel.sample_scales()
    spatial_tables = ALPKernelModel.spatial_tables()
    model = ALPScaleModel.scale_transform(sigmas)
    bits_digest(sigmas) == SIGMAS_BITS_SHA256 || error("sample sigma bits differ")
    bits_digest(Iterators.flatten(spatial_tables)) == SPATIAL_BITS_SHA256 || error("spatial Q bits differ")
    row_major_digest(model.transform) == SCALE_ROW_MAJOR_LE_SHA256 || error("scale matrix bits differ")
    for constant in Float32[0, 100, -100, floatmax(Float32)]
        coefficients = ALPScaleModel.apply_transform(model.transform, fill(constant, 4))
        all(iszero, coefficients[1:3]) && coefficients[4] == constant || error("constant-response constraint differs")
    end
    cases = reference_cases(model.transform)
    rust = generated_rust(sigmas, model.transform, spatial_tables, cases)
    report = generated_report(sigmas, model, cases, rust)
    crate_dir = normpath(joinpath(@__DIR__, "..", ".."))
    write_or_check(joinpath(crate_dir, "src", "extraction", "alp", "tables.rs"), rust, check)
    write_or_check(joinpath(@__DIR__, "alp_table_report.md"), report, check)
    println(check ? "ALP tables match" : "ALP tables generated")
end

abspath(PROGRAM_FILE) == (@__FILE__) && main_tables()
